import { readFileSync, writeFileSync } from 'node:fs';
import { URL } from 'node:url';
import { CandidateSet, filterCandidates } from '../src/core/candidates.ts';
import { chooseMinimax } from '../src/core/minimax.ts';
import { VALID_FEEDBACKS, feedbackKey } from '../src/core/rules.ts';

const entries = VALID_FEEDBACKS.map(feedback => {
  const candidates = filterCandidates(CandidateSet.all(), '0123', feedback);
  const choice = feedback.a === 4 ? null : chooseMinimax(candidates);
  return `  '${feedbackKey(feedback)}': { guess: ${choice ? `'${choice.guess}'` : 'null'}, candidates: ${candidates.size}, worstCase: ${choice?.worstCase ?? 0} },`;
});
const output = `// Generated by npm run solver:table. Do not edit manually.\n// Exact minimax over remaining candidates; lexical tie-break; no sampling.\nexport const OPENING_GUESS = '0123' as const;\nexport const SECOND_GUESS_TABLE = {\n${entries.join('\n')}\n} as const;\n`;
const target = new URL('../src/core/opening-table.generated.ts', import.meta.url);

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    throw new Error('開局表與完整 minimax 計算不一致；請執行 npm run solver:table。');
  }
  console.log('14 項開局表與完整 minimax 完全一致（13 個第二手、1 個終止項目）。');
} else {
  writeFileSync(target, output);
  console.log('已產生 src/core/opening-table.generated.ts（14 項）。');
}
